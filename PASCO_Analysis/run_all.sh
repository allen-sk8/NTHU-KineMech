# 切換至腳本所在目錄
cd "$(dirname "$0")"

echo "=================================================="
echo "   PASCO 力板垂直跳躍自動化分析系統 - 一鍵全流程"
echo "=================================================="
echo ""

echo "[階段一] 轉換原始 .cap 檔案為 CSV 力量數據 ..."
echo "--------------------------------------------------"
python convert_cap_to_csv.py
if [ $? -ne 0 ]; then
    echo "[錯誤] 階段一轉換失敗！請檢查 Python 環境與 inputs 資料夾。"
    exit 1
fi
echo ""

echo "[階段二-A] 分析 CMJ (反向動作蹲跳) 數據 ..."
echo "--------------------------------------------------"
python analyze_cmj.py
if [ $? -ne 0 ]; then
